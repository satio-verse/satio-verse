std::string deny(const Policy& policy,const Call& call) {
  if(!policy.error.empty())return policy.error;
  if(!call.args.is_object()||(call.operation!="unknown"&&call.operation!="read"&&call.operation!="write"))return "工具权限上下文无效";
  std::vector<Leaf> values;size_t budget=kNodes,chars=kStringChars;
  if(!leaves(call.args,values,budget,chars))return "工具参数超过完整权限检查的预算或含无效文字，已拒绝执行";
  if(call.aliases.empty()||call.aliases.size()>32||!valid_text(Json(call.workspace),32768))return "工具权限上下文无效";
  std::vector<std::u32string> aliases;
  for(const auto& alias:call.aliases){if(!valid_text(Json(alias),512,true))return "工具别名无效";aliases.push_back(folded(alias));}
  bool path_rules=false;for(const auto& r:policy.rules.items())if(r["enabled"].boolean()&&r.get_str("kind")=="path")path_rules=true;
  std::vector<std::u32string> paths;std::vector<std::string> commands,urls;
  bool explicit_cwd=false;
  for(const auto& value:values){auto key=utf8(folded(value.key));if(kCommandFields.count(key))commands.push_back(value.value);
    auto extracted=urls_in(value.value);urls.insert(urls.end(),extracted.begin(),extracted.end());
    if(path_rules&&kPathFields.count(key)&&!value.value.empty()&&value.value.find("://")==std::string::npos){std::u32string p;if(!path_norm(value.value,call.workspace,p))return "受限路径检查需要完整路径或已确认的实际工作目录";paths.push_back(p);if(key=="cwd"||key=="workdir")explicit_cwd=true;}}
  if(path_rules&&!commands.empty()&&!explicit_cwd){std::u32string cwd;if(!path_norm(call.workspace,"",cwd))return "命令的实际工作目录未确认，无法完整检查路径限制";paths.push_back(cwd);}
  if(path_rules&&paths.empty()&&call.recursive){std::u32string cwd;if(!path_norm(call.workspace,"",cwd))return "递归搜索的实际根目录未确认";paths.push_back(cwd);}
  for(const auto& rule:policy.rules.items()) {
    if(!rule["enabled"].boolean())continue;
    auto kind=rule.get_str("kind"),raw=rule.get_str("value");bool hit=false;
    if(kind=="instruction")continue;
    if(kind=="tool"){auto pattern=folded(raw);for(const auto& alias:aliases)hit=hit||glob(pattern,alias);}
    else if(kind=="command"){auto pattern=literal(raw);for(const auto& c:commands)hit=hit||contains_phrase(literal(c),pattern);}
    else if(kind=="domain"){std::string domain;normalize_domain(raw,domain);for(const auto& u:urls){std::string host;if(!hostname(u,host))return "网址无法规范化，无法完整检查域名限制";hit=hit||same_domain(host,domain);}}
    else if(kind=="path"){
      auto operation=rule.get_str("operations");if(call.operation!="unknown"&&operation!="all"&&operation!=call.operation)continue;
      std::u32string root;if(!path_norm(raw,"",root))return "共享权限中的路径无法解析";
      for(const auto& path:paths)hit=hit||within(path,root)||(call.recursive&&within(root,path));
      for(const auto& c:commands){auto text=folded(expand_path(c));std::replace(text.begin(),text.end(),U'/',U'\\');
        for(size_t at=text.find(root);at!=std::u32string::npos;at=text.find(root,at+1)){size_t end=at+root.size();if(end==text.size()||space(text[end])||std::u32string(U"\\\"'`;|&<>),").find(text[end])!=std::u32string::npos){hit=true;break;}}}
    }
    if(hit)return "命中黑名单 ["+rule.get_str("id").substr(0,8)+"] "+(rule.get_str("reason").empty()?raw:rule.get_str("reason"));
  }
  return {};
}
