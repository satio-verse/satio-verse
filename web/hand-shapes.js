  offer: { f: [[10, 16, 8, 6], [12, 18, 9, 0], [14, 20, 10, -5], [16, 22, 11, -10]], t: [-8, 4, 6] },
  ball: { f: [[30, 36, 26, 7], [32, 38, 28, 0], [34, 40, 28, -6], [36, 42, 30, -12]], t: [20, 14, 16] },
