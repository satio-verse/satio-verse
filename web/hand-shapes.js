export const GRIPS = ['ball', 'book', 'cup'];

/** 手形 -> 扁平的角度数组 (四指 4x4 + 拇指 3 = 19 个). */
export const flat = (s) => [...s.f.flat(), ...s.t];
export const DOF = 19;

/**
 * 一只手这一帧的目标角度. w: {open, point, lap, offer} 各手形的权重 (0-1, 加起来超过 1 时按比例缩), 剩下的是放松;
 * grip: 握紧程度 (0-1), kind: 握的是什么 (ball / book / cup, 不认识的按 ball; 也可以直接给一个手形 {f, t}). 握持压过其他手形.
 */
export function targetAngles(w, grip = 0, kind = 'ball') {
  // w 里认得的手形都算 (放松是剩下的部分, 握持另算)
  const parts = Object.entries(w).filter(([n, x]) => SHAPES[n] && n !== 'relaxed' && !GRIPS.includes(n) && x > 0);
  const sum = parts.reduce((a, [, x]) => a + Math.max(0, x), 0);
  const k = sum > 1 ? 1 / sum : 1;
  const out = flat(SHAPES.relaxed).map((v) => v * (1 - Math.min(1, sum)));
  for (const [name, x] of parts) {
    if (x <= 0) continue;
    flat(SHAPES[name]).forEach((v, i) => { out[i] += v * x * k; });
  }
  const g = Math.max(0, Math.min(1, grip));
  if (g > 0) {
    const gs = flat(kind && typeof kind === 'object' ? kind : SHAPES[GRIPS.includes(kind) ? kind : 'ball']);
    for (let i = 0; i < DOF; i++) out[i] = out[i] * (1 - g) + gs[i] * g;
  }
  return out;
}

/** 手指的细小起伏 (度): 不握东西、不指向时, 每根手指按各自的相位很慢地弯一点又松一点 (真人的手很少完全静止). */
export function fingerDrift(t, side, amp = 2.5) {
  const ph = side === 'left' ? 0.7 : 0;
  return [0, 1, 2, 3].map((i) => amp * (0.6 * Math.sin(t * (1.3 + 0.37 * i) + ph + i * 1.9) + 0.4 * Math.sin(t * (0.55 + 0.21 * i) + i)));
}
